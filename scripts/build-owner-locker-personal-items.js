const fs = require('fs');
const path = require('path');

const ownerKeys = [
    'bailey', 'brycen', 'chris', 'cody', 'david', 'ethan',
    'jordan', 'keith', 'matthew', 'max', 'mike', 'will'
];
const sourceRoot = path.join(__dirname, '..', 'owners', 'artwork', 'locker');
const outputPath = path.join(__dirname, '..', 'owners', 'locker-personal-items.js');
const supportedExtensions = new Set(['.png', '.jpg', '.jpeg', '.webp', '.gif', '.svg']);

function labelFromFilename(filename) {
    return path.basename(filename, path.extname(filename))
        .replace(/[-_]+/g, ' ')
        .replace(/\s+/g, ' ')
        .trim()
        .replace(/\b\w/g, function (character) { return character.toUpperCase(); });
}

const collection = {};

ownerKeys.forEach(function (ownerKey) {
    const ownerDirectory = path.join(sourceRoot, ownerKey);
    const assets = fs.existsSync(ownerDirectory)
        ? fs.readdirSync(ownerDirectory, { withFileTypes: true })
            .filter(function (entry) {
                return entry.isFile() && supportedExtensions.has(path.extname(entry.name).toLowerCase());
            })
            .map(function (entry) {
                return {
                    label: labelFromFilename(entry.name),
                    asset: 'artwork/locker/' + ownerKey + '/' + entry.name
                };
            })
            .sort(function (left, right) { return left.asset.localeCompare(right.asset); })
        : [];

    collection[ownerKey] = assets;
});

const contents = '/* Generated by scripts/build-owner-locker-personal-items.js. Do not edit directly. */\n' +
    'window.FS5_LOCKER_PERSONAL_ITEMS = ' + JSON.stringify(collection, null, 2) + ';\n';

fs.writeFileSync(outputPath, contents);
console.log('Generated owners/locker-personal-items.js with ' +
    ownerKeys.reduce(function (total, ownerKey) { return total + collection[ownerKey].length; }, 0) +
    ' personal locker item(s).');
